def _fm_fetch(url):
    import ssl
    import urllib.request
    try:
        import certifi   # bundled with CHIRP
        ctx = ssl.create_default_context(cafile=certifi.where())
    except ImportError:
        ctx = ssl.create_default_context()
    req = urllib.request.Request(url, headers={"User-Agent": "CHIRP uvk5_f4hwn_services"})
    with urllib.request.urlopen(req, timeout=30, context=ctx) as f:
        return f.read().decode("latin-1")


def _fm_dms(deg):
    deg = abs(deg)
    d = int(deg)
    m = int((deg - d) * 60)
    return d, m, min(59, round(((deg - d) * 60 - m) * 60))


def fm_stations_near_zip(zipcode):
    """[(frequency Hz, call sign)]: the licensed FM stations within FM_RADIUS_KM,
    on each frequency the strongest there (ERP / distance squared)"""
    import json
    place = json.loads(_fm_fetch(FM_ZIP_URL % zipcode))["places"][0]
    lat, lon = float(place["latitude"]), float(place["longitude"])
    text = _fm_fetch(FM_FCC_URL % ((FM_RADIUS_KM,) + _fm_dms(lat) + ("N" if lat >= 0 else "S",)
                                   + _fm_dms(lon) + ("W" if lon < 0 else "E",)))
    best = {}
    for line in text.splitlines():
        f = [x.strip() for x in line.split("|")]
        if len(f) < 30 or f[3] not in FM_SERVICES or f[9] != "LIC":
            continue
        try:
            hz = int(round(float(f[2].split()[0]) * 10)) * 100000
            erp = max(float(f[14].split()[0] or 0), float(f[15].split()[0] or 0))
            km = next(float(x.split()[0]) for x in f if x.endswith(" km"))
        except (ValueError, IndexError, StopIteration):
            continue
        score = erp / max(km, 1.0) ** 2
        if 87500000 <= hz < 108000000 and (hz not in best or score > best[hz][0]):
            best[hz] = (score, f[1].replace("-FM", "").replace("-LP", ""))
    return [(hz, best[hz][1]) for hz in sorted(best)]


class GroupBank(chirp_common.Bank):
    """A memory group: the firmware's scan list 1-3"""


class GroupBankModel(chirp_common.BankModel):
    """Memory groups (VFO/MR on the radio): a memory can be in any of them"""

    def __init__(self, radio):
        super().__init__(radio, "Groups")
        self._groups = [GroupBank(self, i, "Group %d" % (i + 1)) for i in range(3)]

    def get_num_mappings(self):
        return len(self._groups)

    def get_mappings(self):
        return self._groups

    def _attr(self, memory):
        return self._radio._memobj.ch_attr[memory.number - 1]

    def _in(self, number, idx):
        ch = self._radio._memobj.channel[number - 1]
        if ch.freq in (0, 0xFFFFFFFF):
            return False   # empty (its attribute byte is 0xFF)
        return (int(self._radio._memobj.ch_attr[number - 1].is_scanlistx) >> idx) & 1

    def add_memory_to_mapping(self, memory, bank):
        a = self._attr(memory)
        a.is_scanlistx = int(a.is_scanlistx) | (1 << bank.get_index())

    def remove_memory_from_mapping(self, memory, bank):
        if not self._in(memory.number, bank.get_index()):
            raise Exception("Memory %i is not in %s" % (memory.number, bank.get_name()))
        a = self._attr(memory)
        a.is_scanlistx = int(a.is_scanlistx) & ~(1 << bank.get_index())

    def get_mapping_memories(self, bank):
        return [self._radio.get_memory(n) for n in range(1, 201)
                if self._in(n, bank.get_index())]

    def get_memory_mappings(self, memory):
        if not 1 <= memory.number <= 200:
            return []
        return [g for g in self._groups if self._in(memory.number, g.get_index())]


